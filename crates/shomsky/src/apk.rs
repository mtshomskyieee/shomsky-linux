use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::paths::LearnPaths;
use crate::registry::{load_entry, LearnEntry};

/// Build a minimal unsigned Alpine-style apk from a learn registry entry.
///
/// Layout inside the archive:
///   .PKGINFO
///   usr/local/bin/<name>
///   usr/share/man/man1/<name>.1
///
/// Output: `$HOME/bin/packages/<name>-<ver>-r0.apk`
pub fn publish_apk(paths: &LearnPaths, name: &str) -> Result<PathBuf> {
    crate::name::validate_name(name)?;
    let entry = load_entry(paths, name)?;
    let script = std::fs::read(&entry.script_path)
        .with_context(|| format!("read script {}", entry.script_path))?;
    let man = std::fs::read(&entry.man_path)
        .with_context(|| format!("read man {}", entry.man_path))?;

    paths.ensure_dirs()?;
    let staging = paths.packages_dir().join(format!("{name}-staging"));
    let _ = std::fs::remove_dir_all(&staging);
    let bin_dest = staging.join("usr/local/bin");
    let man_dest = staging.join("usr/share/man/man1");
    std::fs::create_dir_all(&bin_dest)?;
    std::fs::create_dir_all(&man_dest)?;
    let bin_file = bin_dest.join(name);
    std::fs::write(&bin_file, &script)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = std::fs::metadata(&bin_file)?.permissions();
        perms.set_mode(0o755);
        std::fs::set_permissions(&bin_file, perms)?;
    }
    std::fs::write(man_dest.join(format!("{name}.1")), &man)?;

    let pkgver = format!("{}-r0", entry.version);
    let size = script.len() + man.len();
    let pkginfo = format_pkginfo(&entry, &pkgver, size);
    std::fs::write(staging.join(".PKGINFO"), pkginfo)?;

    // Also emit APKBUILD for operators who prefer abuild.
    write_apkbuild(&staging, &entry, &pkgver)?;

    let out_name = format!("{name}-{pkgver}.apk");
    let out_path = paths.packages_dir().join(&out_name);

    // Prefer abuild when available; fall back to tar.gz-as-apk.
    if try_abuild(&staging, &out_path).is_err() {
        build_tar_apk(&staging, &out_path)?;
    }

    let _ = std::fs::remove_dir_all(&staging);
    Ok(out_path)
}

fn format_pkginfo(entry: &LearnEntry, pkgver: &str, size: usize) -> String {
    format!(
        "# Generated by shomsky publish\n\
         pkgname = {name}\n\
         pkgver = {pkgver}\n\
         pkgdesc = {desc}\n\
         url = https://github.com/mtshomskyieee/shomsky-linux\n\
         builddate = {builddate}\n\
         packager = shomsky learn\n\
         size = {size}\n\
         arch = noarch\n\
         origin = {name}\n\
         commit = learn\n\
         maintainer = shomsky learn\n\
         license = MIT\n\
         datahash = \n",
        name = entry.name,
        desc = entry.description.replace('\n', " "),
        builddate = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0),
    )
}

fn write_apkbuild(staging: &Path, entry: &LearnEntry, pkgver: &str) -> Result<()> {
    // pkgver in APKBUILD is upstream version; pkgrel separate.
    let ver = entry.version.as_str();
    let body = format!(
        "# Maintainer: shomsky learn\npkgname={name}\npkgver={ver}\npkgrel=0\npkgdesc=\"{desc}\"\n\
         arch=\"noarch\"\nlicense=\"MIT\"\noptions=\"!check\"\n\npackage() {{\n\
         \tinstall -Dm755 \"$srcdir\"/../usr/local/bin/{name} \\\n\
         \t\t\"$pkgdir\"/usr/local/bin/{name}\n\
         \tinstall -Dm644 \"$srcdir\"/../usr/share/man/man1/{name}.1 \\\n\
         \t\t\"$pkgdir\"/usr/share/man/man1/{name}.1\n}}\n",
        name = entry.name,
        desc = entry.description.replace('"', "'"),
        ver = ver,
    );
    let _ = pkgver; // documented in filename
    std::fs::write(staging.join("APKBUILD"), body)?;
    Ok(())
}

fn try_abuild(_staging: &Path, _out: &Path) -> Result<()> {
    // Full abuild needs alpine-sdk keys and a proper aports tree; skip for default image.
    bail!("abuild not used in default path");
}

fn build_tar_apk(staging: &Path, out: &Path) -> Result<()> {
    // Alpine apk v2 unsigned: gzip-compressed tar of .PKGINFO + payload paths.
    if let Some(parent) = out.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let status = Command::new("tar")
        .args(["-czf"])
        .arg(out)
        .arg("-C")
        .arg(staging)
        .arg(".PKGINFO")
        .arg("usr")
        .status()
        .context("tar czf apk")?;
    if !status.success() {
        bail!("tar failed building {}", out.display());
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::install::{install_artifacts, PromoteArtifacts};
    use std::time::{SystemTime, UNIX_EPOCH};

    fn tmp() -> PathBuf {
        let n = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let p = std::env::temp_dir().join(format!("shomsky-apk-{n}"));
        std::fs::create_dir_all(&p).unwrap();
        p
    }

    #[test]
    fn publish_creates_apk() {
        let home = tmp();
        let paths = LearnPaths::new(&home);
        let art = PromoteArtifacts {
            script: "#!/bin/sh\necho published\n".into(),
            man: ".TH DEMO 1\n.SH NAME\ndemo \\- demo\n".into(),
            bats: "@test \"ok\" { true; }\n".into(),
            description: "demo command".into(),
            flags: vec![],
            completion_words: vec![],
        };
        install_artifacts(&paths, "demo", "demo intent", "echo published", &art).unwrap();
        let apk = publish_apk(&paths, "demo").unwrap();
        assert!(apk.is_file(), "missing {}", apk.display());
        assert!(apk.extension().and_then(|e| e.to_str()) == Some("apk"));
        let _ = std::fs::remove_dir_all(&home);
    }
}
